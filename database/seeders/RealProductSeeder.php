                        'movement_date' => now(),
                        'created_by' => 1,
                    ]);
                }

                $totalSeeded++;
            }

            DB::commit();
            $this->command->info("Successfully seeded {$totalSeeded} products with {$totalImagesCopied} images copied!");
        } catch (\Exception $e) {
            DB::rollBack();
            $this->command->error("Failed seeding products: " . $e->getMessage());
            throw $e;
        }
    }
