                            Picture::create([
                                'product_id' => $product->id,
                                'image_path' => 'products/' . $targetFilename,
                                'is_primary' => ($idx === 0),
                            ]);
                            $totalImagesCopied++;
                        }
                    }
                }

                // Create initial product movement (stock)
                $existingMovement = ProductMovement::where('product_id', $product->id)
                    ->whereIn('movement_type', ['current', 'stored'])
                    ->first();

                if (!$existingMovement) {
                    ProductMovement::create([
                        'product_id' => $product->id,
                        'supply_product_id' => null,
                        'instock_quantity' => $data['stock'] ?? 50,
                        'manufactured_date' => now()->subMonths(3),
